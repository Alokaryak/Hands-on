package com.example.java_tuteDude.classes;

public class VariableContinued {

    public static void main(String[] args) {

        //int data type

        int x = 1000000000;

        // range of int is 32 bits :: -2^31 to 2^31


        //long data type

        long aa = 100000000000L;

        // range of long is 64 bits :: -2^63 to 2^63

        // long also takes up more memory as compared

        short num = 10000;

        // range of short is 16 bits :: -2^15 to 2^15

        // takes up less space as compared to int or long

        byte num1 = 100;

        // range of byte is 8 bits :: -2^7 to 2^7

        double num2 = 32.23789021232123212321222322222222222222222222222222321;

        boolean flag = true; // No zero or one, just true or false

        char character = 'L'; // just a single character

        // A string is a combination of characters
    }
}
